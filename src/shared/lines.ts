const fill = (s: string, vars: Record<string, string | number>) => s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));

export function line(key: string, r: Rng, vars: Record<string, string | number> = {}) {
  return fill(r.pick(LINES[key]), vars);
}

// Применяет разметку {жёстко|мягко}. strong=false — мягкий вариант.
export function voice(text: string, strong: boolean) {
  return text.replace(/\{([^{}|]*)\|([^{}]*)\}/g, (_, hard, soft) => (strong ? hard : soft));
}
